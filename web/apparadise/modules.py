"""Module delivery: one Lmod file per package version, one wrapper per executable.

The design (CLAUDE.md "Module delivery") is an shpc-style generator of our own:

    MODULE_DIR/<name>/<version>.lua           prepends the wrapper directory to PATH
    WRAPPER_DIR/<name>/<version>/<exe>        runs <exe> inside the image with Enroot

Wrappers start the pre-staged read-only squashfs on CephFS
(SQSH_DIR/<target>/<name>-<version>-<target>.sqsh) with `enroot start`, so nothing is
pulled from the registry at run time. The target is chosen on the node, at run time:

    APPARADISE_TARGET set   -> that target (for testing or to force `generic`)
    aarch64                 -> vr       (Vera Rubin NVL72)
    x86_64 and GPU cc >= 12 -> rtx      (RTX PRO 6000 Blackwell, sm_120 + PTX)
    otherwise               -> generic  (sm_70 .. sm_120 + PTX)

and falls back to `generic` when the preferred image was not published. Rubin's compute
capability is still open (QUESTIONS.md), so `vr` is chosen by CPU architecture alone.

Usage (writes files; never touches the registry):

    python -m apparadise.modules --catalog ../catalog --module-dir /shared/modules/apparadise \
        --wrapper-dir /shared/apps/apparadise/bin --sqsh-dir /shared/containers [--dry-run]
"""

from __future__ import annotations

import argparse
import os
import shlex
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .catalog import EXE_RE, NAME_RE, VERSION_RE, load_dir, version_key

GENERATED = "Generated by apparadise. Do not edit: changes are overwritten."


@dataclass(frozen=True)
class Release:
    """One package version with at least one published target."""

    name: str
    title: str
    version: str
    description: str
    homepage: str
    executables: tuple[str, ...]
    targets: tuple[str, ...]  # published targets, e.g. ("rtx", "vr")
    restricted: bool

    def __post_init__(self) -> None:
        # Everything below ends up in file paths, shell scripts and Lua: validate again
        # here, not only in the catalog loader.
        if not NAME_RE.match(self.name) or not VERSION_RE.match(self.version):
            raise ValueError(f"unsafe name or version: {self.name!r} {self.version!r}")
        for e in self.executables:
            if not EXE_RE.match(e):
                raise ValueError(f"unsafe executable name: {e!r}")
        if not set(self.targets) <= {"vr", "rtx", "generic"} or not self.targets:
            raise ValueError(f"bad targets: {self.targets!r}")


def releases(entries: list[dict[str, Any]]) -> list[Release]:
    """Every (package, version) with a published build, from parsed catalog entries."""
    out = []
    for e in entries:
        by_version: dict[str, list[str]] = {}
        for b in e["builds"]:
            if b["status"] == "published":
                by_version.setdefault(b["version"], []).append(b["target"])
        for version, targets in sorted(by_version.items(), key=lambda kv: version_key(kv[0])):
            out.append(Release(
                name=e["name"], title=e["title"], version=version,
                description=e["description"], homepage=e["homepage"],
                executables=tuple(e["executables"]), targets=tuple(sorted(targets)),
                restricted=e["visibility"] == "restricted",
            ))
    return out


def _lua_str(s: str) -> str:
    """A Lua long-bracket string literal that cannot be closed by its content."""
    level = 0
    while f"]{'=' * level}]" in s:
        level += 1
    eq = "=" * level
    return f"[{eq}[{s}]{eq}]"


def lua_module(r: Release, wrapper_dir: str) -> str:
    bin_dir = f"{wrapper_dir}/{r.name}/{r.version}"
    commands = ", ".join(r.executables) or "(none)"
    help_text = (
        f"{r.title} {r.version}\n\n{r.description}\n\n"
        f"Commands: {commands}\n"
        f"Images: {', '.join(f'{r.name}:{r.version}-{t}' for t in r.targets)}\n"
        "Each command runs inside the container image for this node (Enroot, no root).\n"
        "Set APPARADISE_TARGET=generic to force the portable image.\n"
    )
    lines = [
        f"-- {GENERATED}",
        f"help({_lua_str(help_text)})",
        f"whatis({_lua_str('Name: ' + r.title)})",
        f"whatis({_lua_str('Version: ' + r.version)})",
        f"whatis({_lua_str('Description: ' + r.description)})",
    ]
    if r.homepage:
        lines.append(f"whatis({_lua_str('URL: ' + r.homepage)})")
    lines += [
        f"whatis({_lua_str('Targets: ' + ', '.join(r.targets))})",
        f"conflict({_lua_str(r.name)})",
        f"prepend_path(\"PATH\", {_lua_str(bin_dir)})",
        "",
    ]
    return "\n".join(lines)


def wrapper_script(r: Release, exe: str, sqsh_dir: str) -> str:
    q = shlex.quote
    available = " ".join(r.targets)
    sqsh = {t: f"{sqsh_dir}/{t}/{r.name}-{r.version}-{t}.sqsh" for t in r.targets}
    cases = "\n".join(f"    {t}) image={q(path)} ;;" for t, path in sqsh.items())
    return f"""#!/bin/bash
# {GENERATED}
# {r.name} {r.version}: runs `{exe}` inside the container image for this node.
set -euo pipefail

available=" {available} "
pick() {{
  if [[ -n "${{APPARADISE_TARGET:-}}" ]]; then echo "$APPARADISE_TARGET"; return; fi
  case "$(uname -m)" in
    aarch64) echo vr; return ;;
    x86_64)
      local cc
      cc=$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null \\
        | head -n1 | tr -d ' ' || true)
      local major=${{cc%%.*}}
      if [[ "$major" =~ ^[0-9]+$ ]] && (( major >= 12 )); then echo rtx; else echo generic; fi
      return ;;
  esac
  echo generic
}}

target=$(pick)
if [[ "$available" != *" $target "* ]]; then
  if [[ "$available" == *" generic "* ]]; then
    target=generic
  else
    echo "{r.name}/{r.version}: no image for this node (wanted '$target', have:$available)." >&2
    echo "Set APPARADISE_TARGET to one of:$available to override." >&2
    exit 1
  fi
fi
case "$target" in
{cases}
    *) echo "{r.name}/{r.version}: unknown target '$target'" >&2; exit 1 ;;
esac
if [[ ! -r "$image" ]]; then
  echo "{r.name}/{r.version}: image $image is not staged on this system." >&2
  exit 1
fi
# Enroot's system config mounts home, project and scratch and injects the GPU driver and
# the host RDMA/NCCL libraries. The working directory is kept.
exec ${{APPARADISE_ENROOT:-enroot}} start -- "$image" \\
  sh -c 'cd "$1" 2>/dev/null; shift; exec "$@"' sh "$PWD" {q(exe)} "$@"
"""


def _write(path: Path, content: str, mode: int) -> bool:
    """Atomic write; returns True when the file changed."""
    if path.exists() and path.read_text() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return True


def generate(entries: list[dict[str, Any]], *, module_dir: str, wrapper_dir: str,
             sqsh_dir: str, dry_run: bool = False,
             include_restricted: bool = False) -> list[str]:
    """Write module files and wrappers. Returns the paths written (or that would be).

    Restricted packages are skipped unless `include_restricted`: their modules belong in
    a sysadmin-only MODULEPATH, never in the shared one.
    """
    written = []
    for r in releases(entries):
        if r.restricted and not include_restricted:
            continue
        lua = Path(module_dir) / r.name / f"{r.version}.lua"
        files = [(lua, lua_module(r, wrapper_dir), 0o644)]
        for exe in r.executables:
            files.append((Path(wrapper_dir) / r.name / r.version / exe,
                          wrapper_script(r, exe, sqsh_dir), 0o755))
        for path, content, mode in files:
            if dry_run or _write(path, content, mode):
                written.append(str(path))
    return written


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate Lmod modules and Enroot wrappers.")
    p.add_argument("--catalog", required=True, help="folder of catalog/<name>.yml files")
    p.add_argument("--module-dir", required=True)
    p.add_argument("--wrapper-dir", required=True)
    p.add_argument("--sqsh-dir", required=True)
    p.add_argument("--include-restricted", action="store_true",
                   help="also write restricted packages (use a sysadmin-only module dir)")
    p.add_argument("--dry-run", action="store_true", help="list files, write nothing")
    a = p.parse_args(argv)
    for d in (a.module_dir, a.wrapper_dir, a.sqsh_dir):
        if not d.startswith("/"):
            p.error(f"{d}: must be an absolute path")
    paths = generate(load_dir(a.catalog), module_dir=a.module_dir.rstrip("/"),
                     wrapper_dir=a.wrapper_dir.rstrip("/"), sqsh_dir=a.sqsh_dir.rstrip("/"),
                     dry_run=a.dry_run, include_restricted=a.include_restricted)
    for path in paths:
        print(path)
    print(f"{len(paths)} file(s) {'to write' if a.dry_run else 'written'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
